"""Regenerate `watcher/_homoglyphs.py` from the Unicode confusables data.

Usage: python tools/make_homoglyphs.py path/to/confusables.json > watcher/_homoglyphs.py

The input is the `confusables.json` of the `confusable_homoglyphs` package (3.3.1 was used), which is the
Unicode Consortium's confusables.txt (UTR #39) as JSON: for every ASCII letter or digit, the list of characters
that look like it. Only single characters are kept (a character that looks like two, such as "rn" for "m",
is not a letter form). Each character is recorded in the form `watcher.oath` meets it, which is after NFKC,
case folding and NFKD, so a capital that case-folds to another character is stored as that character.
The Unicode data files are used under the Unicode License v3 (see NOTICE).
"""
from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

WIDTH = 36  # pairs per line


def build(data: dict[str, list[dict[str, str]]]) -> dict[str, str]:
    pairs: dict[str, str] = {}
    for letter, entries in sorted(data.items()):
        if len(letter) != 1 or not letter.isascii() or not letter.isalnum():
            continue
        for entry in entries:
            ch = entry["c"]
            if len(ch) != 1 or ch.isascii():
                continue
            for form in (ch, unicodedata.normalize("NFKD", unicodedata.normalize("NFKC", ch)).casefold()):
                if len(form) == 1 and not form.isascii() and unicodedata.category(form) not in ("Mn", "Me", "Cf"):
                    pairs.setdefault(form, letter.lower())
    return pairs


def render(pairs: dict[str, str]) -> str:
    items = [ch + letter for ch, letter in sorted(pairs.items())]
    lines = ["".join(items[i : i + WIDTH]) for i in range(0, len(items), WIDTH)]
    body = "\n".join(f"    {line!r}," for line in lines)
    return (
        '"""Characters that look like an ASCII letter or digit, generated by tools/make_homoglyphs.py.\n\n'
        "From the Unicode Consortium's confusables data (UTR #39), single characters only; see the generator.\n"
        'Do not edit by hand."""\n\n'
        "from __future__ import annotations\n\n"
        "#: Two characters per pair: the lookalike, then the lowercase ASCII letter or digit it imitates.\n"
        f"PAIRS = (\n{body}\n)\n"
    )


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    data = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    sys.stdout.write(render(build(data)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
